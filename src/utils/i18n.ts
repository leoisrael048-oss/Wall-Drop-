export const getLocalizedAchievement = (a: AchievementItem, lang: Language = 'pt'): AchievementItem => {
  const trans = ACHIEVEMENT_DESCS[a.id]?.[lang];
  if (!trans) return a;
  return {
    ...a,
    title: trans.title,
    desc: trans.desc,
    rewardText: trans.rewardText,
  };
};
